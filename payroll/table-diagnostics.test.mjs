import {strict as assert} from "node:assert";
import {makeTable} from "./nl-2026-table-engine.mjs";
import {inspectPayrollTable} from "./table-diagnostics.mjs";
const source={url:"https://www.belastingdienst.nl/test",document:"Synthetic fixture",date:"2026-10-30"};
const selection={period:"maand",residence:"NL",type:"wit",insurance:"VOLLEDIG",credit:false};
const row=(lower,upper,withholding)=>({year:2026,...selection,lower,upper,withholding});
const table=makeTable([row(0,100,5),row(100,200,10)],source);
const d=inspectPayrollTable(table,selection);
assert.equal(d.status,"present");
assert.equal(d.rows,2);
assert.equal(d.firstWage,0);
assert.equal(d.lastWageExclusive,200);
assert.equal(d.gaps,0);
assert.equal(d.overlaps,0);
assert.equal(d.lowerBoundMatched,true);
assert.equal(d.lastCentMatched,true);
assert.equal(d.upperBoundRejected,true);
assert.equal(d.complete,false);
assert.equal(inspectPayrollTable(table,{...selection,residence:"BE"}).status,"missing-table");
assert.throws(()=>inspectPayrollTable(table,{...selection,period:"unknown"}),/Ongeldige/);
console.log("12 tabeldiagnosecontroles geslaagd, uitsluitend synthetische tabeldata.");
