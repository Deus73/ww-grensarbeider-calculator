import {strict as assert} from "node:assert";
import {makeTable} from "./nl-2026-table-engine.mjs";
import {compareNetScenarios} from "./scenario-comparison.mjs";
const source={url:"https://www.belastingdienst.nl/test",document:"Synthetische tabel",date:"2026-10-30"};
const selection={period:"maand",residence:"NL",type:"wit",insurance:"VOLLEDIG",credit:true};
const table=makeTable([{year:2026,...selection,lower:0,upper:3000,withholding:200},{year:2026,...selection,lower:3000,upper:5000,withholding:350}],source);
const a={...selection,wage:2500},b={...selection,wage:4000};
const result=compareNetScenarios(table,a,b,{firstDeductions:50,secondDeductions:100});
assert.equal(result.status,"ok");
assert.equal(result.first.net,2250);
assert.equal(result.second.net,3550);
assert.equal(result.deltaGross,1500);
assert.equal(result.deltaWithholding,150);
assert.equal(result.deltaNet,1300);
assert.equal(compareNetScenarios(table,a,{...b,wage:6000}).status,"unavailable");
assert.equal(compareNetScenarios(table,{...a,special:true},b).status,"unavailable");
assert.equal(compareNetScenarios(table,a,{...b,residence:"BE"}).status,"unavailable");
assert.throws(()=>compareNetScenarios(table,a,b,{secondDeductions:-1}),/Ongeldige/);
assert.throws(()=>compareNetScenarios(null,a,b),/Geen ingeladen/);
console.log("10 scenariovergelijkingscontroles geslaagd met synthetische waarden.");
