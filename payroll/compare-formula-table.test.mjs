import {strict as assert} from "node:assert";
import {makeTable} from "./nl-2026-table-engine.mjs";
import {compareFormulaWithTable} from "./compare-formula-table.mjs";
const source={url:"https://www.belastingdienst.nl/test",document:"Synthetic only",date:"2026-10-31"};
const input={wage:3000,period:"maand",residence:"NL",type:"wit",insurance:"VOLLEDIG",credit:false,ageGroup:"UNDER_AOW"};
const row={year:2026,period:"maand",residence:"NL",type:"wit",insurance:"VOLLEDIG",credit:false,lower:0,upper:5000,withholding:1071.42};
const table=makeTable([row],source);
const good=compareFormulaWithTable(table,[input]);
assert.equal(good.matched,1);
assert.equal(good.mismatched,0);
assert.equal(good.verifiedOfficial,false);
assert.equal(good.results[0].differenceCents,0);
const bad=compareFormulaWithTable(makeTable([{...row,withholding:1071.43}],source),[input]);
assert.equal(bad.mismatched,1);
assert.equal(bad.results[0].differenceCents,-1);
assert.equal(compareFormulaWithTable(table,[{...input,wage:6000}]).unverified,1);
assert.equal(compareFormulaWithTable(table,[{...input,credit:true}]).unverified,1);
assert.throws(()=>compareFormulaWithTable(null,[input]),/gevalideerde/);
assert.throws(()=>compareFormulaWithTable(table,[]),/toetsgevallen/);
assert.throws(()=>compareFormulaWithTable(table,Array(10001).fill(input)),/toetsgevallen/);
console.log("11 vergelijkingstests (synthetische tabel) geslaagd");
