import {strict as assert} from "node:assert";
import {annualTaxCredits2026 as calc} from "./nl-2026-annual-credits.mjs";
const young=(income,workIncome=income)=>calc({income,workIncome,ageGroup:"UNDER_AOW"});
const old=(income,workIncome=income)=>calc({income,workIncome,ageGroup:"FULL_YEAR_AOW"});
assert.equal(young(0).general,3115);
assert.equal(old(0).general,1556);
assert.equal(young(29736).general,3115);
assert.equal(young(78426).general,0);
assert.equal(old(78426).general,0);
assert.equal(young(11965).labour,995.96);
assert.equal(old(11965).labour,497.27);
assert.equal(young(25845).labour,5300.05);
assert.equal(old(25845).labour,2647.04);
assert.equal(young(132921).labour,0);
assert.equal(old(132921).labour,0);
assert.equal(young(30000,0).labour,0);
assert.equal(calc({income:30000,workIncome:30000,ageGroup:"REACHES_AOW_2026"}).status,"unsupported");
for(const n of [-1,NaN,Infinity])assert.throws(()=>young(n),/Ongeldig/);
assert.equal(young(30000).verifiedPayroll,false);
console.log("Annual credit boundary tests passed; not a payroll withholding engine.");
