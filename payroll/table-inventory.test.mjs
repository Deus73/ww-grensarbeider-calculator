import {strict as assert} from "node:assert";
import {makeTable} from "./nl-2026-table-engine.mjs";
import {buildPayrollInventory,inventoryToCsv} from "./table-inventory.mjs";
const source={url:"https://www.belastingdienst.nl/test",document:"synthetisch",date:"2026-10-30"};
const base={year:2026,period:"maand",type:"wit",insurance:"VOLLEDIG",credit:false};
const table=makeTable([{...base,residence:"NL",lower:0,upper:1000,withholding:100},{...base,residence:"NL",lower:1000,upper:2000,withholding:200},{...base,residence:"BE",lower:0,upper:1000,withholding:110}],source);
const inventory=buildPayrollInventory(table,[{period:"week",residence:"NL",type:"wit",insurance:"VOLLEDIG",credit:false},{period:"maand",residence:"NL",type:"wit",insurance:"VOLLEDIG",credit:false}]);
assert.equal(inventory.groups,2);
assert.equal(inventory.totalRows,3);
assert.equal(inventory.entries[0].rows,2);
assert.equal(inventory.entries[0].gaps,0);
assert.equal(inventory.missing.length,1);
assert.equal(inventory.missing[0].selection.period,"week");
assert.equal(inventory.complete,false);
const csv=inventoryToCsv(inventory);
assert.ok(csv.startsWith("year;period;"));
assert.equal(csv.trim().split("\n").length,3);
assert.ok(csv.includes('"BE"'));
assert.throws(()=>buildPayrollInventory(null),/Geen gevalideerde/);
assert.throws(()=>buildPayrollInventory(table,[{period:"wrong"}]),/Ongeldige/);
console.log("12 tabeloverzichtcontroles geslaagd met synthetische gegevens.");
