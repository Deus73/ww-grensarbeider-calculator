import {strict as assert} from "node:assert";
import {createHash} from "node:crypto";
import {bytesToHex,createImportManifest} from "./import-manifest.mjs";
const hash=createHash("sha256").update("abc").digest();
assert.equal(bytesToHex(new Uint8Array(hash)),"ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad");
const input={filename:"loonheffing.csv",size:123,sha256:bytesToHex(new Uint8Array(hash)),source:{url:"https://download.belastingdienst.nl/test.pdf",document:"test",date:"2026-10-31"},groups:2,rows:10};
const manifest=createImportManifest(input);
assert.equal(manifest.year,2026);
assert.equal(manifest.verifiedOfficial,false);
assert.equal(manifest.rows,10);
assert.equal(manifest.sha256,input.sha256);
assert.equal(manifest.source.document,"test");
assert.throws(()=>bytesToHex([]),/hashbytes/);
assert.throws(()=>createImportManifest({...input,sha256:"0"}),/SHA-256/);
assert.throws(()=>createImportManifest({...input,filename:"../evil.csv"}),/bestandsnaam/);
assert.throws(()=>createImportManifest({...input,size:20_000_001}),/bestandsgrootte/);
assert.throws(()=>createImportManifest({...input,rows:0}),/tabelomvang/);
assert.throws(()=>createImportManifest({...input,source:null}),/Bronmetadata/);
console.log("12 importbewijscontroles geslaagd.");
