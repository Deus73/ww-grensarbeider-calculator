import {strict as assert} from "node:assert";
import {makeTable} from "./nl-2026-table-engine.mjs";
import {parseBatchWages,calculatePayrollBatch,batchResultsCsv} from "./batch-calculator.mjs";
const selection={period:"maand",residence:"NL",type:"wit",insurance:"VOLLEDIG",credit:true};
const source={url:"https://www.belastingdienst.nl/test",document:"Synthetic",date:"2026-10-30"};
const table=makeTable([{year:2026,...selection,lower:0,upper:3000,withholding:200},{year:2026,...selection,lower:3000,upper:5000,withholding:350}],source);
assert.deepEqual(parseBatchWages("2500;3000;3500,50"),[2500,3000,3500.5]);
assert.throws(()=>parseBatchWages(""),/Geef/);
assert.throws(()=>parseBatchWages("1e3"),/Ongeldig/);
assert.throws(()=>parseBatchWages("999999999999999999999999"),/te groot/);
const result=calculatePayrollBatch(table,selection,[2500,3000,6000,-1],25);
assert.equal(result.total,4);
assert.equal(result.ok,2);
assert.equal(result.failed,2);
assert.equal(result.results[0].net,2275);
assert.equal(result.results[1].net,2625);
assert.equal(result.results[2].status,"missing-row");
assert.equal(result.results[3].status,"invalid");
assert.ok(batchResultsCsv(result).includes("missing-row"));
console.log("12 batchcontroles geslaagd");
