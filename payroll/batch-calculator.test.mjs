import {strict as assert} from "node:assert";
import {makeTable} from "./nl-2026-table-engine.mjs";
import {parseBatchWages,calculatePayrollBatch,batchResultsCsv} from "./batch-calculator.mjs";
const sel={period:"maand",residence:"NL",type:"wit",insurance:"VOLLEDIG",credit:true};
const table=makeTable([{year:2026,...sel,lower:0,upper:3000,withholding:200},{year:2026,...sel,lower:3000,upper:5000,withholding:350}],{url:"https://www.belastingdienst.nl/test",document:"Synthetic",date:"2026-10-30"});
assert.deepEqual(parseBatchWages("2500\n3000; 3500,50"),[2500,3000,3500.5]);
assert.throws(()=>parseBatchWages(""),/Geef/);
assert.throws(()=>parseBatchWages("3.123"),/Ongeldig/);
assert.throws(()=>parseBatchWages("1e3"),/Ongeldig/);
assert.throws(()=>parseBatchWages(Array(501).fill("1").join(";")),/maximaal/);
const report=calculatePayrollBatch(table,sel,[2500,3000,6000,-1],25);
assert.equal(report.total,4);
assert.equal(report.ok,2);
assert.equal(report.failed,2);
assert.equal(report.results[0].net,2275);
assert.equal(report.results[1].net,2625);
assert.equal(report.results[2].status,"missing-row");
assert.equal(report.results[3].status,"invalid");
const csv=batchResultsCsv(report);
assert.equal(csv.trim().split("\n").length,5);
assert.ok(csv.includes('"missing-row"'));
assert.throws(()=>calculatePayrollBatch(table,sel,[]),/Geef/);
console.log("15 batchlooncontroles geslaagd met synthetische belastinggegevens.");
